import React, { useState } from 'react';
import { X, CheckCircle2, AlertCircle, HelpCircle, Award, RotateCcw } from 'lucide-react';

interface QuizModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const QuizModal: React.FC<QuizModalProps> = ({ isOpen, onClose }) => {
  const [currentQ, setCurrentQ] = useState(0);
  const [selectedAnswers, setSelectedAnswers] = useState<number[]>([]);
  const [showResults, setShowResults] = useState(false);

  if (!isOpen) return null;

  const questions = [
    {
      q: '1. What is the fundamental difference between Frontend and Backend?',
      opts: [
        'Frontend runs in the user browser creating the UI; Backend runs on the server managing data, auth, and business logic.',
        'Frontend is only for graphics/design; Backend is where all HTML and CSS are executed.',
        'Frontend is for databases; Backend is for buttons and styling.',
        'There is no difference; modern web applications run everything exclusively in the browser.',
      ],
      correct: 0,
      exp: 'The Frontend runs client-side (HTML/CSS/React in the browser) while the Backend runs server-side (Node.js/Supabase/Postgres) securely handling secrets and persistence.',
    },
    {
      q: '2. What primary role does a Database like Supabase (PostgreSQL) play in a SaaS?',
      opts: [
        'It speeds up JavaScript download times in the user browser.',
        'It safely persists application data, user profiles, and records across browser refreshes and sessions.',
        'It converts Python code into machine binary code automatically.',
        'It replaces the need for any frontend styling.',
      ],
      correct: 1,
      exp: 'Without a database, all user state vanishes on page refresh. A database stores persistent rows, tables, and credentials with row-level security.',
    },
    {
      q: '3. What distinguishes an AI Coding Agent (e.g. OpenCode) from a standard AI Chatbot?',
      opts: [
        'An AI Chatbot can only answer questions in a chat window; an AI Coding Agent has workspace access to read, create, and edit project files directly.',
        'AI Coding Agents do not use LLMs; they only run spellcheck.',
        'There is no difference; they are identical tools.',
        'AI Chatbots are only for mobile apps.',
      ],
      correct: 0,
      exp: 'Coding Agents have workspace awareness, tool execution capabilities, multi-file editing, and direct terminal/file system interaction.',
    },
    {
      q: '4. Why is Git & GitHub essential before deploying an app to Netlify?',
      opts: [
        'Because Netlify cannot run any code unless it is written in assembly language.',
        'Git tracks version history and GitHub acts as the cloud trigger that automated CI/CD deployment pipelines pull from.',
        'Git is only needed if you work in an office building.',
        'GitHub compresses images so they load faster.',
      ],
      correct: 1,
      exp: 'GitHub hosts your repository in the cloud. Netlify connects to your GitHub repository and triggers automatic production builds on every `git push`.',
    },
    {
      q: '5. What happens when an application is "Deployed" to Netlify?',
      opts: [
        'Your laptop must remain open and plugged in 24/7 so other users can see it.',
        'Your code is built into static production assets distributed across global edge CDN servers with a public HTTPS URL.',
        'The code is deleted and turned into a PDF document.',
        'It only works if other users are on your local home Wi-Fi network.',
      ],
      correct: 1,
      exp: 'Deployment moves your software from localhost onto high-availability cloud servers with public IP routing, automatic SSL encryption, and instant global access.',
    },
    {
      q: '6. Why must developers review, test, and debug code generated by AI?',
      opts: [
        'Because AI models can hallucinate incorrect API signatures, introduce security loopholes, or overlook subtle edge cases.',
        'Because AI code is always illegal to use in commercial software.',
        'Because computers cannot run AI-generated text files.',
        'You actually never need to review AI code; it is guaranteed 100% bug-free.',
      ],
      correct: 0,
      exp: 'AI is a powerful accelerator, but the engineer remains responsible for architecture, security validation, testing boundary cases, and system reliability.',
    },
  ];

  const handleSelect = (optIndex: number) => {
    const updated = [...selectedAnswers];
    updated[currentQ] = optIndex;
    setSelectedAnswers(updated);
  };

  const handleNext = () => {
    if (currentQ < questions.length - 1) {
      setCurrentQ(currentQ + 1);
    } else {
      setShowResults(true);
    }
  };

  const score = selectedAnswers.reduce((acc, ans, idx) => {
    return ans === questions[idx].correct ? acc + 1 : acc;
  }, 0);

  const resetQuiz = () => {
    setCurrentQ(0);
    setSelectedAnswers([]);
    setShowResults(false);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-forest-darkest/60 backdrop-blur-md animate-fadeIn">
      <div className="relative w-full max-w-xl bg-white rounded-3xl p-6 sm:p-10 border-4 border-forest shadow-brutal-lg overflow-hidden">
        
        {/* Close Button */}
        <button
          onClick={onClose}
          className="absolute top-4 right-4 p-2 rounded-full bg-forest-surface hover:bg-forest/15 text-forest transition-colors"
        >
          <X className="w-5 h-5" />
        </button>

        {!showResults ? (
          <div>
            {/* Header */}
            <div className="flex items-center justify-between mb-4">
              <span className="text-xs font-black px-2.5 py-1 rounded-full bg-neon text-forest-darkest border border-forest">
                Question {currentQ + 1} of {questions.length}
              </span>
              <span className="font-mono text-xs font-bold text-muted">
                Part 5 Knowledge Check
              </span>
            </div>

            {/* Question Title */}
            <h3 className="font-sans font-black text-lg sm:text-xl text-forest-darkest mb-6 leading-snug">
              {questions[currentQ].q}
            </h3>

            {/* Options */}
            <div className="space-y-3 mb-6">
              {questions[currentQ].opts.map((opt, idx) => {
                const isSelected = selectedAnswers[currentQ] === idx;
                return (
                  <button
                    key={idx}
                    onClick={() => handleSelect(idx)}
                    className={`w-full text-left p-3.5 sm:p-4 rounded-2xl border-2 text-xs sm:text-sm font-bold transition-all flex items-start gap-3 ${
                      isSelected
                        ? 'bg-neon/20 border-forest text-forest-darkest shadow-sm ring-2 ring-forest/30'
                        : 'bg-forest-surface border-forest/15 text-forest-darkest hover:border-forest hover:bg-white'
                    }`}
                  >
                    <span className={`w-5 h-5 rounded-md border flex items-center justify-center flex-shrink-0 text-xs font-black mt-0.5 ${
                      isSelected ? 'bg-forest text-neon border-forest' : 'bg-white border-forest/30'
                    }`}>
                      {String.fromCharCode(65 + idx)}
                    </span>
                    <span>{opt}</span>
                  </button>
                );
              })}
            </div>

            {/* Bottom Actions */}
            <div className="flex items-center justify-between pt-4 border-t border-muted-border/60">
              <button
                disabled={currentQ === 0}
                onClick={() => setCurrentQ(currentQ - 1)}
                className="px-4 py-2 rounded-xl border border-forest text-forest font-black text-xs disabled:opacity-30 disabled:pointer-events-none hover:bg-forest-surface"
              >
                Previous
              </button>

              <button
                disabled={selectedAnswers[currentQ] === undefined}
                onClick={handleNext}
                className="px-6 py-2.5 rounded-xl bg-forest text-neon font-black text-xs sm:text-sm border-2 border-neon disabled:opacity-30 disabled:pointer-events-none hover:bg-forest-mid transition-all shadow-sm"
              >
                {currentQ === questions.length - 1 ? 'See Score' : 'Next Question →'}
              </button>
            </div>
          </div>
        ) : (
          <div className="text-center py-4">
            <div className="w-16 h-16 rounded-3xl bg-neon border-2 border-forest flex items-center justify-center mx-auto mb-4 shadow-brutal-sm">
              <Award className="w-8 h-8 text-forest-darkest stroke-[2.5]" />
            </div>

            <h3 className="font-sans font-black text-2xl sm:text-3xl text-forest-darkest mb-1">
              Quiz Completed!
            </h3>
            <p className="text-xs sm:text-sm font-bold text-muted mb-4">
              You scored <span className="text-forest font-black text-lg">{score}</span> out of {questions.length} correct.
            </p>

            <div className="p-4 rounded-2xl bg-forest-surface border border-forest/20 text-xs text-forest-darkest font-semibold mb-6 text-left space-y-2">
              <p>🎯 <strong>Key Insight:</strong> Software development is fundamentally about orchestration — connecting frontend interfaces, cloud databases, and AI tooling with confidence.</p>
            </div>

            <div className="flex gap-3">
              <button
                onClick={resetQuiz}
                className="flex-1 py-3 rounded-2xl border-2 border-forest text-forest font-black text-xs hover:bg-forest-surface flex items-center justify-center gap-1.5"
              >
                <RotateCcw className="w-4 h-4" /> Retake
              </button>
              <button
                onClick={onClose}
                className="flex-1 py-3 rounded-2xl bg-forest text-neon font-black text-xs border-2 border-neon hover:bg-forest-mid shadow-sm"
              >
                Back to Workshop
              </button>
            </div>
          </div>
        )}

      </div>
    </div>
  );
};

